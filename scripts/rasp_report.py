def geomean(x):
    x = np.asarray(x, float)
    x = x[np.isfinite(x) & (x > 0)]
    return float(np.exp(np.log(x).mean())) if len(x) else float("nan")


def style(ax):
    ax.set_facecolor(SURFACE)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    ax.tick_params(colors=TEXT2, labelsize=9)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)


def save(fig, path, formats=("png",)):
    """Writes path with every requested extension (png for the repo, pdf for the report)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    out = []
    for ext in formats:
        p = path.with_suffix("." + ext)
        fig.savefig(p, dpi=160, facecolor=SURFACE, bbox_inches="tight")
        out.append(p)
    return out


def tex_escape(s):
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
            .replace("#", r"\#").replace("$", r"\$").replace("~", r"\textasciitilde{}"))


class TexWriter:
    """Collects \\setstat values and tables for one generated .tex file."""

    def __init__(self, path):
        self.path = Path(path) if path else None
        self.lines = []

    @staticmethod
    def key(name):
        """Keys are letters, digits and '-' only (easy to type in the report): <100k -> lt100k, tree_nobe -> tree-nobe."""
        name = str(name).replace("<", "lt").replace(">", "gt")
        return re.sub(r"[^A-Za-z0-9:-]+", "-", name).strip("-")

    def stat(self, key, value, fmt="{:.2f}"):
        key = self.key(key)
        if isinstance(value, (float, np.floating)):
            text = "--" if not np.isfinite(value) else fmt.format(value)
        else:
            text = str(value)
        self.lines.append(f"\\setstat{{{key}}}{{{text}}}")

    def table(self, name, header, rows, align=None):
        """A bare tabular, stored as the stat `table:<name>` (the report wraps it in its own table float)."""
        name = self.key(name)
        align = align or "l" + "r" * (len(header) - 1)
        body = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + r" \\", "\\midrule"]
        body += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
        body += ["\\bottomrule", "\\end{tabular}"]
        self.lines.append(f"\\setstat{{table:{name}}}{{%\n" + "\n".join(body) + "}")

    def write(self):
        if not self.path:
            return None
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("% Generated by scripts/analyze_*.py -- do not edit by hand.\n" + "\n".join(self.lines) + "\n")
        return self.path
