"""Shared helpers for the analysis scripts: figure style and report output.

Figures: the palette and axis style of the Phase 2-3 figures (validated with the dataviz palette checker: CVD and
normal-vision separation pass; three slots are below 3:1 contrast on the surface, so every figure carries a legend
and the numbers also go to a table). Colors follow the entity: a method keeps its slot in every figure.

Report: the LaTeX report never contains a hand-typed result. Each script writes `\\setstat{key}{value}` lines and
tabulars into docs/report/generated/; the report prints them with `\\stat{key}` (an unknown key prints ??key and
warns, so a missing number is visible in the PDF).
"""
